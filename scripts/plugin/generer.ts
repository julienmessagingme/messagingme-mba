/**
 * `npm run plugin:generer` : écrit la FAQ (`scripts/plugin/faq.ts`, la seule source) là où elle se publie.
 *  - `plugin/skills/faq/SKILL.md`, la skill que Claude lit (en anglais, puis en français) ;
 *  - le bloc FAQ des pages développeurs de la vitrine, entre leurs marques `<!-- faq:debut -->` et `<!-- faq:fin -->`,
 *    quand la page les porte (lot 10, livraison B), avec son balisage `FAQPage` pour les moteurs.
 * `tests/plugin-faq.test.ts` refait ces sorties et exige l'égalité au caractère près : une réponse changée sans relancer
 * le script rend la CI rouge.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { CATALOGUE_MCP } from '../../web/lib/partage/catalogue-mcp';
import { FAQ } from './faq';

type Langue = 'fr' | 'en';

/** Un nom d'outil MCP cité dans une réponse, reconnu au catalogue : rien d'autre n'est mis en forme. */
const OUTIL_RE = new RegExp(`\\b(${Object.keys(CATALOGUE_MCP).join('|')})\\b`, 'g');

export const MARQUE_DEBUT = '<!-- faq:debut, généré par npm run plugin:generer depuis scripts/plugin/faq.ts : ne pas modifier à la main -->';
export const MARQUE_FIN = '<!-- faq:fin -->';

/** Les pages de la vitrine qui portent la FAQ, et leur langue. */
export const PAGES_FAQ: ReadonlyArray<{ chemin: string; langue: Langue }> = [
  { chemin: 'site/developpeurs/index.html', langue: 'fr' },
  { chemin: 'site/en/developers/index.html', langue: 'en' },
];

export function skillFaq(): string {
  const md = (t: string) => t.replace(OUTIL_RE, '`$1`');
  const lignes = [
    '---',
    'name: faq',
    'description: Answers to frequent questions about Messaging Me (official WhatsApp API, what Meta bills, the 24-hour '
      + 'window, templates, numbers, plans, updating this plugin). Use when the user asks about Messaging Me or WhatsApp '
      + 'limits, or hits one of these problems.',
    '---',
    '',
    '<!-- GENERATED by `npm run plugin:generer` from scripts/plugin/faq.ts in the messagingme-mba repository: do not edit by hand. -->',
    '',
    '# Messaging Me FAQ',
    '',
    'Answer in the user’s language, with the matching version below (English, then French). Do not add facts that are not '
      + 'here, above all about what Meta charges: if the answer is not in this FAQ, say so and point to '
      + 'https://console.messagingme.app/developers/api.',
    '',
  ];
  for (const e of FAQ) {
    lignes.push(`## ${e.question.en}`, '', md(e.reponse.en), '', `**FR · ${e.question.fr}**`, '', md(e.reponse.fr), '');
  }
  return lignes.join('\n');
}

const echapper = (t: string): string => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** Le texte d'une réponse en HTML : les outils en code, l'adresse de la grille de Meta en lien. */
function enHtml(t: string): string {
  return echapper(t)
    .replace(OUTIL_RE, '<code>$1</code>')
    .replace(/https:\/\/[^\s<]+[^\s<.,;:)]/g, (u) => `<a href="${u}">${u.replace(/^https:\/\//, '')}</a>`);
}

export function blocFaqVitrine(langue: Langue): string {
  const ld = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    inLanguage: langue === 'fr' ? 'fr-FR' : 'en-US',
    mainEntity: FAQ.map((e) => ({
      '@type': 'Question', name: e.question[langue], acceptedAnswer: { '@type': 'Answer', text: e.reponse[langue] },
    })),
  };
  return [
    MARQUE_DEBUT,
    '<div class="dev-faq">',
    ...FAQ.map((e) => `  <details id="faq-${e.id}"><summary>${echapper(e.question[langue])}</summary><p>${enHtml(e.reponse[langue])}</p></details>`),
    '</div>',
    `<script type="application/ld+json">${JSON.stringify(ld).replace(/</g, '\\u003c')}</script>`,
    MARQUE_FIN,
  ].join('\n');
}

/** La page avec son bloc FAQ à jour, ou telle quelle si elle ne porte pas les marques. */
export function pageAvecFaq(html: string, langue: Langue): string {
  const i = html.indexOf(MARQUE_DEBUT);
  if (i < 0) return html;
  const j = html.indexOf(MARQUE_FIN, i);
  if (j < 0) throw new Error('marque de fin de la FAQ absente');
  return html.slice(0, i) + blocFaqVitrine(langue) + html.slice(j + MARQUE_FIN.length);
}

async function main(): Promise<void> {
  const racine = (p: string) => fileURLToPath(new URL(`../../${p}`, import.meta.url));
  writeFileSync(racine('plugin/skills/faq/SKILL.md'), skillFaq());
  for (const { chemin, langue } of PAGES_FAQ) {
    if (!existsSync(racine(chemin))) continue;
    const avant = readFileSync(racine(chemin), 'utf8');
    const apres = pageAvecFaq(avant, langue);
    if (apres !== avant) writeFileSync(racine(chemin), apres);
  }
  console.log('plugin/skills/faq/SKILL.md réécrit, et la FAQ des pages qui portent ses marques');
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
